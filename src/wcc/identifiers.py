"""Opaque identifier generation.

Specification 7 requires every ID to be an opaque string generated by WCC. IDs are
prefixed so a value found in a log or an exported capability file names its own
kind, and the random part is drawn from :mod:`secrets` so an ID never leaks a
counter, a timestamp, or a host detail.
"""

from __future__ import annotations

import secrets

_RANDOM_BYTES = 12


def new_id(prefix: str) -> str:
    """Return a fresh opaque identifier such as ``sess_9f3c...``."""
    if not prefix:
        raise ValueError("prefix is required so an identifier names its own kind")
    return f"{prefix}_{secrets.token_hex(_RANDOM_BYTES)}"
